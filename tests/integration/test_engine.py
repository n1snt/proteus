@pytest.mark.integration
async def test_executor_recovers_a_concurrent_index_crash_gap(database: str) -> None:
    table_id, column_id, index_id = object_id(), object_id(), object_id()
    baseline = {
        'tables': [
            {
                'id': table_id,
                'name': 'events',
                'columns': [
                    {
                        'id': column_id,
                        'name': 'occurred_at',
                        'data_type': 'timestamp',
                        'nullable': False,
                        'default': 'CURRENT_TIMESTAMP',
                        'identity': None,
                    }
                ],
                'constraints': [],
                'indexes': [],
            }
        ]
    }
    target = {
        'tables': [
            {
                **baseline['tables'][0],
                'indexes': [
                    {
                        'id': index_id,
                        'name': 'events_occurred_at_idx',
                        'columns': [column_id],
                        'unique': False,
                    }
                ],
            }
        ]
    }
    async with await psycopg.AsyncConnection.connect(database, row_factory=dict_row) as conn:
        await conn.execute(
            'CREATE TABLE events (occurred_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP)'
        )
        await conn.commit()
        await executor.initialize_tracking(conn, 'environment-2', 'revision-0', baseline)
    plan = {
        'steps': [
            {
                'id': 'create-index',
                'sql': 'CREATE INDEX CONCURRENTLY events_occurred_at_idx ON events (occurred_at)',
                'description': 'create online index',
                'transactional': False,
                'impact': 'index',
                'operation': {
                    'kind': 'create_index',
                    'schema': 'public',
                    'name': 'events_occurred_at_idx',
                    'table': 'events',
                    'unique': False,
                    'columns': ['occurred_at'],
                },
            }
        ]
    }
    async with await psycopg.AsyncConnection.connect(database, row_factory=dict_row) as conn:
        await executor._prepare_execution(
            conn,
            'environment-2',
            'execution-2',
            'revision-0',
            'revision-1',
            target,
            plan,
        )
    async with await psycopg.AsyncConnection.connect(database, autocommit=True) as conn:
        await conn.execute(
            'CREATE INDEX CONCURRENTLY events_occurred_at_idx ON events (occurred_at)'
        )
    assert await executor.execute_plan(
        database,
        'public',
        'environment-2',
        'execution-2',
        'revision-0',
        'revision-1',
        target,
        plan,
    ) == {'status': 'succeeded'}


@pytest.mark.integration
async def test_executor_marks_committed_not_valid_phase_needs_attention(database: str) -> None:
    table_id, column_id, constraint_id, index_id = (
        object_id(),
        object_id(),
        object_id(),
        object_id(),
    )
    baseline = {
        'tables': [
            {
                'id': table_id,
                'name': 'values_for_validation',
                'columns': [
                    {
                        'id': column_id,
                        'name': 'value',
                        'data_type': 'integer',
                        'nullable': True,
                        'default': None,
                        'identity': None,
                    }
                ],
                'constraints': [],
                'indexes': [],
            }
        ]
    }
    target = {
        'tables': [
            {
                **baseline['tables'][0],
                'constraints': [
                    {
                        'id': constraint_id,
                        'name': 'values_positive',
                        'kind': 'check',
                        'columns': [column_id],
                        'expression': 'value > 0',
                    }
                ],
                'indexes': [
                    {
                        'id': index_id,
                        'name': 'values_for_validation_idx',
                        'columns': [column_id],
                        'unique': False,
                    }
                ],
            }
        ]
    }
    async with await psycopg.AsyncConnection.connect(database, row_factory=dict_row) as conn:
        await conn.execute('CREATE TABLE values_for_validation (value integer)')
        await conn.execute('INSERT INTO values_for_validation VALUES (-1)')
        await conn.commit()
        await executor.initialize_tracking(conn, 'environment-validation', 'revision-0', baseline)
    plan = {
        'steps': [
            {
                'id': 'add-not-valid',
                'sql': 'ALTER TABLE values_for_validation ADD CONSTRAINT values_positive CHECK (value > 0) NOT VALID',
                'description': 'add check',
                'transactional': True,
                'impact': 'metadata',
                'operation': {'kind': 'add_constraint'},
            },
            {
                'id': 'validate',
                'sql': 'ALTER TABLE values_for_validation VALIDATE CONSTRAINT values_positive',
                'description': 'validate check',
                'transactional': True,
                'impact': 'scan',
                'operation': {'kind': 'validate_constraint'},
            },
            {
                'id': 'later-index',
                'sql': 'CREATE INDEX CONCURRENTLY values_for_validation_idx ON values_for_validation (value)',
                'description': 'make the plan multi-phase',
                'transactional': False,
                'impact': 'index',
                'operation': {
                    'kind': 'create_index',
                    'schema': 'public',
                    'name': 'values_for_validation_idx',
                    'table': 'values_for_validation',
                    'unique': False,
                    'columns': ['value'],
                },
            },
        ]
    }
    result = await executor.execute_plan(
        database,
        'public',
        'environment-validation',
        'execution-validation',
        'revision-0',
        'revision-1',
        target,
        plan,
    )
    assert result['status'] == 'needs_attention'
    async with await psycopg.AsyncConnection.connect(database, row_factory=dict_row) as conn:
        constraint = await conn.execute(
            "SELECT convalidated FROM pg_constraint WHERE conname = 'values_positive'"
        )
        assert (await constraint.fetchone())['convalidated'] is False
        state = await conn.execute('SELECT active_execution FROM "_proteus".state')
        assert (await state.fetchone())['active_execution'] == 'execution-validation'
        migration = await conn.execute(
            'SELECT state FROM "_proteus".migrations WHERE execution_id = %s',
            ('execution-validation',),
        )
        assert (await migration.fetchone())['state'] == 'needs_attention'
    async with await psycopg.AsyncConnection.connect(database) as conn:
        await conn.execute('UPDATE values_for_validation SET value = 1')
        await conn.commit()
    retry = await executor.execute_plan(
        database,
        'public',
        'environment-validation',
        'execution-validation',
        'revision-0',
        'revision-1',
        target,
        plan,
    )
    async with await psycopg.AsyncConnection.connect(database, row_factory=dict_row) as conn:
        captured = await catalog.introspect(conn, 'public', reference=target)
    assert captured['unsupported'] == []
    assert captured['snapshot'] == schema.validate_snapshot(target)
    assert retry == {'status': 'succeeded'}
